"""Deterministic, approval-gated project scaffolding inside workspace only."""

import hashlib
import json
import os
import re
import uuid
from datetime import datetime, timezone
from pathlib import Path

from core.audit import AuditLog


class ScaffoldingError(RuntimeError):
    """Raised when a project scaffold cannot be safely proposed or applied."""


class ProjectScaffolder:
    MAX_FILES = 10
    MAX_FILE_BYTES = 128 * 1024
    MAX_TOTAL_BYTES = 1024 * 1024
    PROJECT_NAME_RE = re.compile(r"^[a-z][a-z0-9_-]{0,39}$")

    def __init__(self, project_root):
        self.root = Path(project_root).resolve()
        self.workspace = self.root / "workspace"
        self.proposals = self.workspace / "scaffold_proposals"
        self.generated = self.workspace / "generated_projects"
        self.audit = AuditLog(self.root)

    @staticmethod
    def _now():
        return datetime.now(timezone.utc).isoformat()

    @staticmethod
    def _sha256(data):
        return hashlib.sha256(data).hexdigest()

    def _proposal_path(self, proposal_id):
        if not isinstance(proposal_id, str) or not re.fullmatch(
            r"[0-9a-f]{32}", proposal_id
        ):
            raise ScaffoldingError("Invalid scaffold proposal ID.")
        return self.proposals / f"{proposal_id}.json"

    def _safe_relative_file(self, relative):
        if not isinstance(relative, str) or not relative or len(relative) > 240:
            raise ScaffoldingError("Invalid scaffold file path.")
        path = Path(relative)
        if (
            path.is_absolute()
            or ".." in path.parts
            or not path.parts
            or any(part.startswith(".") for part in path.parts)
            or "\\" in relative
        ):
            raise ScaffoldingError("Unsafe scaffold file path.")
        allowed = {".py", ".mjs", ".js", ".cjs", ".json", ".md", ".toml", ".txt"}
        if path.suffix.lower() not in allowed:
            raise ScaffoldingError("Unsupported scaffold file extension.")
        return path

    def _template_files(self, project_name, language, description, requirements):
        readme = (
            f"# {project_name}\n\n"
            f"{description}\n\n"
            "This project was generated by ELON's deterministic scaffold workflow.\n"
            "No dependencies were installed and no source code was executed.\n"
        )
        requirements_doc = (
            f"# Requirements for {project_name}\n\n"
            f"{requirements.strip()}\n"
        )

        if language == "python":
            return {
                "README.md": readme,
                "REQUIREMENTS.md": requirements_doc,
                "main.py": (
                    f'PROJECT_NAME = "{project_name}"\n'
                    f'DESCRIPTION = {description!r}\n\n'
                    "def main():\n"
                    "    return {\n"
                    "        \"project\": PROJECT_NAME,\n"
                    "        \"description\": DESCRIPTION,\n"
                    "        \"status\": \"scaffolded\",\n"
                    "    }\n\n"
                    'if __name__ == "__main__":\n'
                    "    print(main())\n"
                ),
                "tests/test_smoke.py": (
                    "import unittest\n\n"
                    "from main import main\n\n\n"
                    "class ScaffoldSmokeTests(unittest.TestCase):\n"
                    "    def test_main_returns_project_metadata(self):\n"
                    "        result = main()\n"
                    "        self.assertEqual(result[\"status\"], \"scaffolded\")\n"
                    f"        self.assertEqual(result[\"project\"], \"{project_name}\")\n\n\n"
                    'if __name__ == "__main__":\n'
                    "    unittest.main()\n"
                ),
                "pyproject.toml": (
                    "[project]\n"
                    f'name = "{project_name.replace("_", "-")}"\n'
                    'version = "0.1.0"\n'
                    'requires-python = ">=3.10"\n'
                    "dependencies = []\n"
                ),
            }

        if language == "javascript":
            return {
                "README.md": readme,
                "REQUIREMENTS.md": requirements_doc,
                "package.json": json.dumps({
                    "name": project_name.replace("_", "-"),
                    "version": "0.1.0",
                    "private": True,
                    "type": "module",
                    "scripts": {"test": "node --test"},
                    "dependencies": {},
                }, indent=2) + "\n",
                "src/index.mjs": (
                    f'export const PROJECT_NAME = "{project_name}";\n'
                    f"export const DESCRIPTION = {json.dumps(description)};\n\n"
                    "export function main() {\n"
                    "  return {\n"
                    "    project: PROJECT_NAME,\n"
                    "    description: DESCRIPTION,\n"
                    '    status: "scaffolded",\n'
                    "  };\n"
                    "}\n"
                ),
                "test/smoke.test.mjs": (
                    'import test from "node:test";\n'
                    'import assert from "node:assert/strict";\n'
                    'import { main } from "../src/index.mjs";\n\n'
                    'test("main returns project metadata", () => {\n'
                    '  const result = main();\n'
                    '  assert.equal(result.status, "scaffolded");\n'
                    f'  assert.equal(result.project, "{project_name}");\n'
                    "});\n"
                ),
            }

        raise ScaffoldingError("Unsupported scaffold language.")

    def propose_template(
        self,
        project_name,
        language="python",
        description="",
        requirements="",
    ):
        if (
            not isinstance(project_name, str)
            or not self.PROJECT_NAME_RE.fullmatch(project_name)
        ):
            raise ScaffoldingError(
                "Project name must be lowercase letters, digits, '_' or '-', "
                "starting with a letter."
            )
        if language not in ("python", "javascript"):
            raise ScaffoldingError("Language must be python or javascript.")
        if not isinstance(description, str) or not description.strip():
            raise ScaffoldingError("Project description is required.")
        if len(description) > 500:
            raise ScaffoldingError("Project description exceeds 500 characters.")
        if not isinstance(requirements, str) or len(requirements) > 5000:
            raise ScaffoldingError("Requirements must be text up to 5000 characters.")

        if self.workspace.is_symlink():
            raise ScaffoldingError("Workspace must not be a symlink.")
        self.workspace.mkdir(parents=True, exist_ok=True)
        if self.proposals.is_symlink() or self.generated.is_symlink():
            raise ScaffoldingError("Scaffold metadata/destination paths must not be symlinks.")
        target = self.generated / project_name
        if target.exists() or target.is_symlink():
            raise ScaffoldingError("Generated project destination already exists.")

        files = self._template_files(
            project_name,
            language,
            description.strip(),
            requirements.strip(),
        )
        if not 1 <= len(files) <= self.MAX_FILES:
            raise ScaffoldingError("Invalid scaffold file count.")

        file_records = []
        total_bytes = 0
        for relative, text in sorted(files.items()):
            path = self._safe_relative_file(relative)
            data = text.encode("utf-8")
            if len(data) > self.MAX_FILE_BYTES:
                raise ScaffoldingError("A scaffold file exceeds the size limit.")
            total_bytes += len(data)
            file_records.append({
                "path": path.as_posix(),
                "content": text,
                "sha256": self._sha256(data),
                "size": len(data),
            })

        if total_bytes > self.MAX_TOTAL_BYTES:
            raise ScaffoldingError("Scaffold exceeds the total size limit.")

        self.proposals.mkdir(parents=True, exist_ok=True)
        self.generated.mkdir(parents=True, exist_ok=True)
        proposal_id = uuid.uuid4().hex
        record = {
            "schema_version": 1,
            "proposal_id": proposal_id,
            "status": "pending",
            "project_name": project_name,
            "language": language,
            "description": description.strip(),
            "requirements": requirements.strip(),
            "target": f"workspace/generated_projects/{project_name}",
            "files": file_records,
            "total_bytes": total_bytes,
            "created_at": self._now(),
            "approved_at": None,
            "applied_at": None,
        }
        self._write_record(self._proposal_path(proposal_id), record)
        self._audit("PROJECT_SCAFFOLD_PROPOSED", {
            "proposal_id": proposal_id,
            "project_name": project_name,
            "language": language,
            "file_count": len(file_records),
        })
        return record

    def _write_record(self, path, record):
        if path.is_symlink():
            raise ScaffoldingError("Scaffold metadata path must not be a symlink.")
        path.parent.mkdir(parents=True, exist_ok=True)
        temporary = path.with_name(
            path.name + ".tmp." + uuid.uuid4().hex
        )
        payload = json.dumps(
            record,
            ensure_ascii=False,
            sort_keys=True,
            indent=2,
        ).encode("utf-8")
        descriptor = os.open(
            temporary,
            os.O_WRONLY | os.O_CREAT | os.O_EXCL,
            0o600,
        )
        try:
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(payload)
                handle.flush()
                os.fsync(handle.fileno())
            os.replace(temporary, path)
            self._fsync_directory(path.parent)
        except Exception:
            try:
                temporary.unlink(missing_ok=True)
            except OSError:
                pass
            raise

    @staticmethod
    def _fsync_directory(path):
        try:
            descriptor = os.open(path, os.O_RDONLY)
            try:
                os.fsync(descriptor)
            finally:
                os.close(descriptor)
        except OSError:
            pass

    def _fsync_audit(self):
        path = self.audit.path
        if not path.exists():
            return
        with path.open("rb") as handle:
            os.fsync(handle.fileno())

    def _audit_contains(self, event_name, proposal_id):
        if not self.audit.path.exists():
            return False
        if not self.audit.verify():
            raise ScaffoldingError("Audit log integrity check failed.")
        try:
            with self.audit.path.open("r", encoding="utf-8") as handle:
                for line in handle:
                    item = json.loads(line)
                    if (
                        isinstance(item, dict)
                        and item.get("event") == event_name
                        and isinstance(item.get("details"), dict)
                        and item["details"].get("proposal_id") == proposal_id
                    ):
                        return True
        except (OSError, UnicodeError, json.JSONDecodeError):
            raise ScaffoldingError("Audit log could not be inspected.") from None
        return False

    def _audit(self, event_name, details):
        proposal_id = details["proposal_id"]
        if not self._audit_contains(event_name, proposal_id):
            self.audit.append(event_name, details)
        self._fsync_audit()

    def _load(self, proposal_id):
        path = self._proposal_path(proposal_id)
        if self.workspace.is_symlink() or self.proposals.is_symlink():
            raise ScaffoldingError("Scaffold proposal path contains a symlink.")
        if path.is_symlink() or not path.is_file():
            raise ScaffoldingError("Scaffold proposal was not found.")
        try:
            path.resolve(strict=True).relative_to(
                self.proposals.resolve(strict=True)
            )
        except (OSError, ValueError):
            raise ScaffoldingError("Scaffold proposal escaped its storage directory.") from None
        try:
            record = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeError, json.JSONDecodeError):
            raise ScaffoldingError("Scaffold proposal is unreadable.") from None
        if (
            not isinstance(record, dict)
            or record.get("schema_version") != 1
            or record.get("proposal_id") != proposal_id
            or record.get("status") not in (
                "pending", "approved", "applying", "recovery_required", "applied"
            )
        ):
            raise ScaffoldingError("Scaffold proposal metadata is invalid.")
        return record

    def list_proposals(self):
        if not self.proposals.exists():
            return []
        records = []
        for path in sorted(self.proposals.glob("*.json")):
            if path.is_symlink() or not path.is_file():
                continue
            try:
                record = json.loads(path.read_text(encoding="utf-8"))
            except (OSError, UnicodeError, json.JSONDecodeError):
                continue
            if isinstance(record, dict):
                records.append({
                    "proposal_id": record.get("proposal_id"),
                    "project_name": record.get("project_name"),
                    "language": record.get("language"),
                    "status": record.get("status"),
                    "target": record.get("target"),
                    "file_count": len(record.get("files", []))
                    if isinstance(record.get("files"), list) else 0,
                })
        return records

    def approve(self, proposal_id):
        record = self._load(proposal_id)
        if record["status"] == "approved":
            return record
        if record["status"] != "pending":
            raise ScaffoldingError("Only pending scaffold proposals can be approved.")
        self._validate_record_files(record)
        self._target_path(record)

        self._audit("PROJECT_SCAFFOLD_APPROVED", {
            "proposal_id": proposal_id,
            "project_name": record["project_name"],
        })
        record["status"] = "approved"
        record["approved_at"] = self._now()
        self._write_record(self._proposal_path(proposal_id), record)
        return record

    def _validate_record_files(self, record):
        files = record.get("files")
        if not isinstance(files, list) or not 1 <= len(files) <= self.MAX_FILES:
            raise ScaffoldingError("Scaffold file manifest is invalid.")

        total = 0
        expected = {}
        for item in files:
            if not isinstance(item, dict):
                raise ScaffoldingError("Scaffold file entry is invalid.")
            path = self._safe_relative_file(item.get("path"))
            text = item.get("content")
            if not isinstance(text, str):
                raise ScaffoldingError("Scaffold file content is invalid.")
            data = text.encode("utf-8")
            digest = self._sha256(data)
            if (
                len(data) > self.MAX_FILE_BYTES
                or item.get("sha256") != digest
                or item.get("size") != len(data)
            ):
                raise ScaffoldingError("Scaffold file hash or size is invalid.")
            total += len(data)
            if path.as_posix() in expected:
                raise ScaffoldingError("Duplicate scaffold file path.")
            expected[path.as_posix()] = data

        if total > self.MAX_TOTAL_BYTES or total != record.get("total_bytes"):
            raise ScaffoldingError("Scaffold total size is invalid.")
        return expected

    def _target_path(self, record):
        if not self.PROJECT_NAME_RE.fullmatch(record.get("project_name", "")):
            raise ScaffoldingError("Invalid scaffold project name.")
        target = self.generated / record["project_name"]
        if target.is_symlink():
            raise ScaffoldingError("Scaffold destination must not be a symlink.")
        if target.resolve().parent != self.generated.resolve():
            raise ScaffoldingError("Scaffold destination escaped generated_projects.")
        if self.generated.is_symlink() or self.workspace.is_symlink():
            raise ScaffoldingError("Scaffold destination contains a symlink.")
        return target

    def _write_new_file(self, target, relative, data):
        path = target / Path(relative)
        current = target
        for part in Path(relative).parts[:-1]:
            current = current / part
            if current.exists() and current.is_symlink():
                raise ScaffoldingError("Scaffold path contains a symlink.")
            current.mkdir(exist_ok=True)

        if path.is_symlink():
            raise ScaffoldingError("Scaffold target file is a symlink.")
        if path.exists():
            if not path.is_file() or self._sha256(path.read_bytes()) != self._sha256(data):
                raise ScaffoldingError(
                    f"Existing scaffold file differs from proposal: {relative}"
                )
            return False

        flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL
        descriptor = os.open(path, flags, 0o600)
        try:
            with os.fdopen(descriptor, "wb") as handle:
                handle.write(data)
                handle.flush()
                os.fsync(handle.fileno())
        except Exception:
            try:
                os.close(descriptor)
            except OSError:
                pass
            raise
        self._fsync_directory(path.parent)
        return True

    def _apply_record(self, record, recovery=False):
        proposal_id = record["proposal_id"]
        expected = self._validate_record_files(record)
        target = self._target_path(record)

        if not recovery:
            if record["status"] != "approved":
                raise ScaffoldingError("Scaffold proposal requires explicit approval.")
            if target.exists() or target.is_symlink():
                raise ScaffoldingError("Generated project destination already exists.")
            record["status"] = "applying"
            self._write_record(self._proposal_path(proposal_id), record)
            target.mkdir(parents=False, exist_ok=False)
        else:
            if record["status"] not in ("applying", "recovery_required"):
                raise ScaffoldingError("Scaffold proposal is not recoverable.")
            target.mkdir(parents=False, exist_ok=True)

        try:
            expected_paths = set(expected)
            for current, directories, filenames in os.walk(
                target,
                topdown=True,
                followlinks=False,
            ):
                current_path = Path(current)
                for directory in directories:
                    directory_path = current_path / directory
                    if directory_path.is_symlink():
                        raise ScaffoldingError("Generated project contains a symlink.")
                    relative_directory = directory_path.relative_to(
                        target
                    ).as_posix()
                    if not any(
                        expected_path.startswith(relative_directory + "/")
                        for expected_path in expected_paths
                    ):
                        raise ScaffoldingError(
                            f"Unexpected directory in generated project: {relative_directory}"
                        )
                for filename in filenames:
                    existing = current_path / filename
                    if existing.is_symlink():
                        raise ScaffoldingError("Generated project contains a symlink.")
                    relative = existing.relative_to(target).as_posix()
                    if relative == ".elon-scaffold.json":
                        continue
                    if relative not in expected_paths:
                        raise ScaffoldingError(
                            f"Unexpected file in generated project: {relative}"
                        )

            for relative, data in expected.items():
                self._write_new_file(target, relative, data)

            manifest = {
                "proposal_id": proposal_id,
                "project_name": record["project_name"],
                "language": record["language"],
                "files": {
                    relative: self._sha256(data)
                    for relative, data in expected.items()
                },
            }
            manifest_path = target / ".elon-scaffold.json"
            manifest_bytes = json.dumps(
                manifest,
                sort_keys=True,
                indent=2,
            ).encode("utf-8")
            if manifest_path.exists():
                if manifest_path.is_symlink() or manifest_path.read_bytes() != manifest_bytes:
                    raise ScaffoldingError("Existing scaffold manifest does not match.")
            else:
                descriptor = os.open(
                    manifest_path,
                    os.O_WRONLY | os.O_CREAT | os.O_EXCL,
                    0o600,
                )
                with os.fdopen(descriptor, "wb") as handle:
                    handle.write(manifest_bytes)
                    handle.flush()
                    os.fsync(handle.fileno())
            self._fsync_directory(target)

            self._audit("PROJECT_SCAFFOLD_APPLIED", {
                "proposal_id": proposal_id,
                "project_name": record["project_name"],
                "file_count": len(expected),
                "target": record["target"],
            })
            record["status"] = "applied"
            record["applied_at"] = self._now()
            self._write_record(self._proposal_path(proposal_id), record)
            return record
        except Exception:
            record["status"] = "recovery_required"
            self._write_record(self._proposal_path(proposal_id), record)
            raise

    def apply(self, proposal_id):
        record = self._load(proposal_id)
        if record["status"] == "applied":
            return record
        return self._apply_record(record, recovery=False)

    def recover(self, proposal_id, confirm_stopped=False):
        if confirm_stopped is not True:
            raise ScaffoldingError(
                "Recovery requires confirmation that the original process stopped."
            )
        record = self._load(proposal_id)
        if record["status"] == "applied":
            return record
        if record["status"] not in ("applying", "recovery_required"):
            raise ScaffoldingError(
                "Only an interrupted scaffold application can be recovered."
            )
        recovered = self._apply_record(record, recovery=True)
        self._audit("PROJECT_SCAFFOLD_RECOVERED", {
            "proposal_id": proposal_id,
            "project_name": recovered["project_name"],
        })
        return recovered
